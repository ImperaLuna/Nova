//! Generates the wire names in `ui/daemon/protocol.js` from the types novad
//! serves, so the UI's copy can't drift from novad's.
//!
//! The names come from serde itself (`nova_carrier::names`), so `rename_all`
//! and new variants carry over with no list to keep: the commands from
//! novad's [`router`](crate::requests::router), the topics from
//! [`TOPICS`](crate::topics::TOPICS), the events from [`events`], and the
//! rest from `nova-protocol`. Feature ids come from the folders in
//! `features/`. The text replaces what sits between [`BEGIN`] and [`END`]
//! in protocol.js; the helper functions below that block stay hand-written.
//!
//! The groups whose names come from several crates (commands, events,
//! topics) keep each name where protocol.js already has it, and add a new
//! one at the end of its group, so moving a message type from
//! `nova-protocol` into a feature's api crate leaves the file as it is.
//!
//! `protocol_js_is_current` fails when the file is stale;
//! `just protocol-js` rewrites it.

use nova_carrier::names::{names_of, tagged_names_of};
use nova_protocol::*;
use std::path::Path;

/// First line of the generated block in protocol.js. It still names
/// nova-protocol, where the generator was until IMP-373, so the file stays
/// byte for byte the same during the novad move (IMP-381 updates it).
pub const BEGIN: &str = "// BEGIN GENERATED by `just protocol-js` from crates/nova-protocol. Don't edit.";
/// Last line of the generated block.
pub const END: &str = "// END GENERATED";

/// The names of every event type novad sends: the shared `Event`, then each
/// moved feature's, by feature name.
fn events() -> Vec<&'static str> {
    [
        tagged_names_of::<Event>("event"),
        tagged_names_of::<nova_launcher_api::Event>("event"),
        tagged_names_of::<nova_network_api::Event>("event"),
        tagged_names_of::<nova_notifications_api::Event>("event"),
        tagged_names_of::<nova_resources_api::Event>("event"),
        tagged_names_of::<nova_tray_api::Event>("event"),
    ]
    .concat()
}

/// One group of `var <PREFIX>_<NAME> = "<name>";` lines.
struct Group {
    comment: &'static str,
    prefix: &'static str,
    names: Vec<String>,
}

impl Group {
    fn new(comment: &'static str, prefix: &'static str, names: &[&str]) -> Self {
        Group { comment, prefix, names: names.iter().map(|name| name.to_string()).collect() }
    }

    /// A group of `names` in the order protocol.js (`current`) has them,
    /// new names after, in the order given.
    fn in_file_order(comment: &'static str, prefix: &'static str, names: &[&str], current: &str) -> Self {
        let position = |name: &str| {
            let line = format!("var {prefix}_{} = \"{name}\";", constant_name(name));
            current.lines().position(|current_line| current_line == line).unwrap_or(usize::MAX)
        };
        let mut ordered = names.to_vec();
        // Stable: names protocol.js lacks keep their order, at the end.
        ordered.sort_by_key(|name| position(name));
        Group::new(comment, prefix, &ordered)
    }
}

/// Feature ids: the folders in `features/` that hold a `feature.toml`.
fn feature_ids(features: &Path) -> Vec<String> {
    let mut ids: Vec<String> = std::fs::read_dir(features)
        .unwrap_or_else(|error| panic!("{}: {error}", features.display()))
        .map(|entry| entry.unwrap().path())
        .filter(|folder| folder.join("feature.toml").is_file())
        .map(|folder| folder.file_name().unwrap().to_string_lossy().into_owned())
        .collect();
    ids.sort();
    ids
}

/// The groups, `current` being protocol.js as it is.
fn groups(features: &Path, current: &str) -> Vec<Group> {
    vec![
        Group::in_file_order("Commands a client sends (Command).", "CMD", crate::requests::router().names(), current),
        Group::in_file_order(
            "Events novad sends (Event). Each topic's events carry the topic's name.",
            "EVENT",
            &events(),
            current,
        ),
        Group::in_file_order("Event topics a client subscribes to (Topic).", "TOPIC", crate::topics::names(), current),
        Group::new("What a compositor can report or do (Capability).", "CAPABILITY", names_of::<Capability>()),
        Group::new("Panels a toggle event names (Panel).", "PANEL", names_of::<Panel>()),
        Group::new("step_workspace's directions (Step).", "STEP", names_of::<Step>()),
        Group::new("The volume keys a volume event carries (VolumeKey).", "VOLUME", names_of::<VolumeKey>()),
        Group { comment: "Feature ids (features/<id>/feature.toml).", prefix: "FEATURE", names: feature_ids(features) },
        Group::new(
            "Launcher providers built into novad (PROVIDER_*).",
            "PROVIDER",
            &[nova_launcher_api::PROVIDER_APPS, nova_launcher_api::PROVIDER_FILES],
        ),
        Group::new("Power menu actions (PowerAction).", "POWER", names_of::<nova_power_api::PowerAction>()),
        Group::new("What the capture toolbar takes (CaptureMode).", "CAPTURE", names_of::<CaptureMode>()),
        Group::new("The screenshot card's buttons (ScreenshotAction).", "SHOT", names_of::<ScreenshotAction>()),
        Group::new(
            "How much a notification matters (Urgency).",
            "URGENCY",
            names_of::<nova_notifications_api::Urgency>(),
        ),
        Group::new("The now-playing panel's buttons (MediaAction).", "MEDIA", names_of::<MediaAction>()),
        Group::new("What a media player is doing (PlaybackStatus).", "PLAYBACK", names_of::<PlaybackStatus>()),
    ]
}

/// The numbers the UI checks before sending, as `(name, value, comment)`.
fn limits() -> [(&'static str, u64, &'static str); 7] {
    let size = |limit: usize| u64::try_from(limit).unwrap();
    [
        (
            "LAUNCHER_SEARCH_MAX_CHARS",
            size(nova_launcher_api::LAUNCHER_SEARCH_MAX_CHARS),
            "novad refuses longer launcher_search queries.",
        ),
        ("MEDIA_PLAYER_MAX_BYTES", size(MEDIA_PLAYER_MAX_BYTES), "novad refuses longer media player ids."),
        (
            "WIFI_PASSWORD_MAX_BYTES",
            size(nova_network_api::WIFI_PASSWORD_MAX_BYTES),
            "novad refuses longer Wi-Fi passwords.",
        ),
        (
            "WPA_PASSWORD_MIN_BYTES",
            size(nova_network_api::WPA_PASSWORD_MIN_BYTES),
            "novad refuses shorter WPA passwords.",
        ),
        (
            "RAW_BYTE_BASE",
            u64::from(nova_launcher_api::RAW_BYTE_BASE),
            "Paths on the wire: this plus a byte (0x80 to 0xFF) stands for that byte of a name that isn't UTF-8.",
        ),
        ("REQUEST_MAX_BYTES", REQUEST_MAX_BYTES, "novad closes the connection on a longer request line."),
        (
            "NETWORK_TRAFFIC_HISTORY_SECS",
            nova_network_api::NETWORK_TRAFFIC_HISTORY_SECS,
            "How far back a network_traffic event's history goes, in seconds (one sample each).",
        ),
    ]
}

/// `"focus_workspace"` -> `FOCUS_WORKSPACE`, `"ai-usage"` -> `AI_USAGE`.
fn constant_name(name: &str) -> String {
    name.to_uppercase().replace(['-', '.'], "_")
}

/// The generated block, [`BEGIN`] and [`END`] included, for the features in
/// the `features` folder, `current` being protocol.js as it is.
pub fn generated(features: &Path, current: &str) -> String {
    let mut js = String::new();
    let mut line = |text: String| {
        js.push_str(&text);
        js.push('\n');
    };
    line(BEGIN.to_string());
    line(String::new());
    line(format!("var VERSION = {PROTOCOL_VERSION};"));
    for (name, value, comment) in limits() {
        line(String::new());
        line(format!("// {comment}"));
        line(format!("var {name} = {value};"));
    }
    for group in groups(features, current) {
        line(String::new());
        line(format!("// {}", group.comment));
        for name in &group.names {
            line(format!("var {}_{} = \"{name}\";", group.prefix, constant_name(name)));
        }
    }
    line(String::new());
    line(END.to_string());
    js
}

/// `protocol_js` with its generated block replaced by `block`.
pub fn with_block(protocol_js: &str, block: &str) -> String {
    let start = protocol_js.find(BEGIN).expect("protocol.js has no BEGIN GENERATED line");
    let end = protocol_js[start..].find(END).expect("protocol.js has no END GENERATED line") + start;
    // Everything after END's line stays, whatever ends that line.
    let after = protocol_js[end..].find('\n').map_or(protocol_js.len(), |newline| end + newline + 1);
    format!("{}{block}{}", &protocol_js[..start], &protocol_js[after..])
}

#[test]
fn protocol_js_is_current() {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
    let path = root.join("ui/daemon/protocol.js");
    let current = std::fs::read_to_string(&path).unwrap();
    let expected = with_block(&current, &generated(&root.join("features"), &current));
    if std::env::var_os("NOVA_WRITE_PROTOCOL_JS").is_some() {
        std::fs::write(&path, &expected).unwrap();
        return;
    }
    assert!(current == expected, "ui/daemon/protocol.js is stale: run `just protocol-js`");
}

/// Wire names live only in the generated block: a `var` written by hand
/// next to the functions would escape the check above and could shadow a
/// generated one.
#[test]
fn protocol_js_declares_names_only_in_the_block() {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
    let js = std::fs::read_to_string(root.join("ui/daemon/protocol.js")).unwrap();
    let outside = with_block(&js, "");
    let declared: Vec<&str> = outside.lines().filter(|line| line.starts_with("var ")).collect();
    assert!(declared.is_empty(), "protocol.js declares names outside the generated block: {declared:?}");
}

#[test]
fn names_follow_serde() {
    assert_eq!(names_of::<Step>(), ["next", "previous"]);
    assert_eq!(names_of::<Panel>(), Panel::ALL.map(Panel::name));
    let commands = tagged_names_of::<Command>("cmd");
    assert!(commands.contains(&"subscribe"));
    assert!(tagged_names_of::<nova_network_api::Event>("event").contains(&"network_traffic"));
}

#[test]
fn constant_names() {
    assert_eq!(constant_name("focus_workspace"), "FOCUS_WORKSPACE");
    assert_eq!(constant_name("ai-usage"), "AI_USAGE");
}

#[test]
fn block_is_replaced_in_place() {
    let js = format!("head\n{BEGIN}\nold\n{END}\ntail\n");
    assert_eq!(with_block(&js, "new\n"), "head\nnew\ntail\n");
}

#[test]
fn names_are_unique() {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
    let current = std::fs::read_to_string(root.join("ui/daemon/protocol.js")).unwrap();
    let block = generated(&root.join("features"), &current);
    let mut seen = std::collections::HashSet::new();
    for name in block.lines().filter_map(|line| line.strip_prefix("var ")?.split(' ').next()) {
        assert!(seen.insert(name), "two wire names both become {name}");
    }
}

/// A launcher provider is a view some feature's manifest slots in.
#[test]
fn providers_are_manifest_views() {
    let features = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../features");
    let slotted = |provider: &str| {
        std::fs::read_dir(&features).unwrap().flatten().any(|feature| {
            std::fs::read_to_string(feature.path().join("feature.toml"))
                .is_ok_and(|manifest| manifest.contains(&format!("view = \"{provider}\"")))
        })
    };
    for provider in [nova_launcher_api::PROVIDER_APPS, nova_launcher_api::PROVIDER_FILES] {
        assert!(slotted(provider), "no feature.toml slots in the {provider:?} provider");
    }
}
