//! Generates the wire names in `ui/daemon/protocol.js` from this crate's
//! types, so the UI's copy can't drift from novad's.
//!
//! The names come from serde itself: deserializing an unknown variant makes
//! serde report every name the enum accepts ([`Variants`] catches that list),
//! so `rename_all` and new variants carry over with no list to keep. Feature
//! ids come from the folders in `features/`. The text replaces what sits
//! between [`BEGIN`] and [`END`] in protocol.js; the helper functions below
//! that block stay hand-written.
//!
//! `protocol_js_is_current` fails when the file is stale;
//! `just protocol-js` rewrites it.

use super::*;
use serde::de::value::{MapDeserializer, StrDeserializer};
use std::path::Path;

/// First line of the generated block in protocol.js.
pub const BEGIN: &str = "// BEGIN GENERATED by `just protocol-js` from crates/nova-protocol. Don't edit.";
/// Last line of the generated block.
pub const END: &str = "// END GENERATED";

/// An error that keeps the names serde says an enum accepts.
#[derive(Debug)]
struct Variants(Option<&'static [&'static str]>);

impl fmt::Display for Variants {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "variants: {:?}", self.0)
    }
}

impl std::error::Error for Variants {}

impl serde::de::Error for Variants {
    fn custom<T: fmt::Display>(_message: T) -> Self {
        Variants(None)
    }

    fn unknown_variant(_variant: &str, expected: &'static [&'static str]) -> Self {
        Variants(Some(expected))
    }
}

/// A name no enum here accepts, so serde lists the ones it does.
const UNKNOWN: &str = "";

/// Every wire name of a plain enum (`"focus_workspace"`, ...), in
/// declaration order.
fn names_of<'de, T: Deserialize<'de>>() -> &'static [&'static str] {
    caught::<T>(T::deserialize(StrDeserializer::<Variants>::new(UNKNOWN)).err())
}

/// Every wire name of an enum tagged by `tag` (`#[serde(tag = "cmd")]`).
fn tagged_names_of<'de, T: Deserialize<'de>>(tag: &'static str) -> &'static [&'static str] {
    let message = MapDeserializer::<_, Variants>::new(std::iter::once((tag, UNKNOWN)));
    caught::<T>(T::deserialize(message).err())
}

fn caught<T>(error: Option<Variants>) -> &'static [&'static str] {
    match error {
        Some(Variants(Some(names))) => names,
        _ => panic!(
            "serde listed no variants for {}: only a derived Deserialize of a plain or tagged enum does",
            std::any::type_name::<T>()
        ),
    }
}

/// One group of `var <PREFIX>_<NAME> = "<name>";` lines.
struct Group {
    comment: &'static str,
    prefix: &'static str,
    names: Vec<String>,
}

impl Group {
    fn new(comment: &'static str, prefix: &'static str, names: &[&str]) -> Self {
        Group { comment, prefix, names: names.iter().map(|name| name.to_string()).collect() }
    }
}

/// Feature ids: the folders in `features/` that hold a `feature.toml`.
fn feature_ids(features: &Path) -> Vec<String> {
    let mut ids: Vec<String> = std::fs::read_dir(features)
        .unwrap_or_else(|error| panic!("{}: {error}", features.display()))
        .map(|entry| entry.unwrap().path())
        .filter(|folder| folder.join("feature.toml").is_file())
        .map(|folder| folder.file_name().unwrap().to_string_lossy().into_owned())
        .collect();
    ids.sort();
    ids
}

